import tempfile
import unittest
import base64
from contextlib import contextmanager
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

import py7zr

from extractor import ArchiveRejected, Limits, PasswordNeeded, extract_archive


class ProtectedArchiveTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)

    def tearDown(self):
        self.temp.cleanup()

    def archive(self, headers=False, entries=None):
        path = self.root / 'encrypted.7z'
        with py7zr.SevenZipFile(path, 'w', password='correct', header_encryption=headers) as archive:
            for name, data in entries or [('folder/a.txt', b'hello')]:
                archive.writestr(data, name)
        return path

    def test_real_encrypted_7z_requires_password_with_and_without_hidden_names(self):
        for headers in [False, True]:
            with self.subTest(headers=headers), self.assertRaises(PasswordNeeded):
                extract_archive(self.archive(headers), self.root / 'out', limits=Limits(min_free=0))

    def test_real_encrypted_7z_wrong_password_is_retryable(self):
        for headers in [False, True]:
            with self.subTest(headers=headers), self.assertRaises(PasswordNeeded):
                extract_archive(self.archive(headers), self.root / 'out', password='wrong', limits=Limits(min_free=0))

    def test_real_encrypted_7z_correct_password_extracts_bytes(self):
        for headers in [False, True]:
            with self.subTest(headers=headers):
                output = self.root / ('out' + str(headers))
                files = extract_archive(self.archive(headers), output, password='correct', limits=Limits(min_free=0))
                self.assertEqual([p.read_bytes() for p in files], [b'hello'])
                self.assertEqual(files[0].relative_to(output).as_posix(), 'folder/a.txt')

    def test_encrypted_7z_keeps_output_and_file_count_limits(self):
        path = self.archive(entries=[('a', b'hello'), ('b', b'world')])
        for limits in [Limits(max_total=4, min_free=0), Limits(max_files=1, min_free=0), Limits(max_entries=1, min_free=0)]:
            with self.subTest(limits=limits), self.assertRaises(ArchiveRejected):
                extract_archive(path, self.root / 'out', password='correct', limits=limits)

    def test_encrypted_7z_rejects_normalized_duplicate_paths(self):
        path = self.archive(entries=[('a', b'one'), ('./a', b'two')])
        with self.assertRaises(ArchiveRejected):
            extract_archive(path, self.root / 'out', password='correct', limits=Limits(min_free=0))

    def test_legacy_and_aes_zip_password_detection_and_decryption(self):
        # Small fixtures generated by7-Zip with password 'correct' and plaintext 'hello'.
        fixtures = [
            'UEsDBBQAAQAAAM2YZF2GphA2EQAAAAUAAAAFAAAAYS50eHTQOYrBnrEZBDFNoe4oLPSQFlBLAQI/ABQAAQAAAM2YZF2GphA2EQAAAAUAAAAFACQAAAAAAAAAIAAAAAAAAABhLnR4dAoAIAAAAAAAAQAYALWk0odMbN0BAAAAAAAAAAAAAAAAAAAAAFBLBQYAAAAAAQABAFcAAAA0AAAAAAA=',
            'UEsDBDMAAQBjAM2YZF0AAAAAIQAAAAUAAAAFAAsAYS50eHQBmQcAAgBBRQMAADD6M2lhTp06GTU/wpZl9lNWyhLbrIftZEQX56GR+jnNIVBLAQI/ADMAAQBjAM2YZF0AAAAAIQAAAAUAAAAFAC8AAAAAAAAAIAAAAAAAAABhLnR4dAoAIAAAAAAAAQAYALWk0odMbN0BAAAAAAAAAAAAAAAAAAAAAAGZBwACAEFFAwAAUEsFBgAAAAABAAEAYgAAAE8AAAAAAA==',
        ]
        for index, fixture in enumerate(fixtures):
            path = self.root / f'{index}.zip'
            path.write_bytes(base64.b64decode(fixture))
            for password in [None, 'wrong']:
                with self.subTest(index=index, password=password), self.assertRaises(PasswordNeeded):
                    extract_archive(path, self.root / f'bad-{index}-{password}', password=password, limits=Limits(min_free=0))
            files = extract_archive(path, self.root / f'good-{index}', password='correct', limits=Limits(min_free=0))
            self.assertEqual(files[0].read_bytes(), b'hello')

    def test_encrypted_7z_traversal_names_are_rejected_before_writing(self):
        for name in ['../escape', '/etc/passwd', '..\\escape', 'C:/escape']:
            path = self.root / 'malicious.7z'
            with py7zr.SevenZipFile(path, 'w', password='correct') as archive:
                archive.writestr(b'bad', 'placeholder')
                archive.header.files_info.files[-1]['filename'] = name
            with self.subTest(name=name), self.assertRaises(ArchiveRejected):
                extract_archive(path, self.root / 'out', password='correct', limits=Limits(min_free=0))
        self.assertFalse((self.root / 'escape').exists())

    def test_encrypted_7z_symlink_is_rejected(self):
        link = self.root / 'link'
        link.symlink_to('/etc/passwd')
        path = self.root / 'link.7z'
        with py7zr.SevenZipFile(path, 'w', password='correct') as archive:
            archive.write(link, 'link')
        with self.assertRaises(ArchiveRejected):
            extract_archive(path, self.root / 'out', password='correct', limits=Limits(min_free=0))

    def test_sevenzip_writer_enforces_actual_bytes_despite_lying_header(self):
        path = self.root / 'fake.7z'
        path.write_bytes(b'7z\xbc\xaf\x27\x1c')

        @contextmanager
        def reader(*args, **kwargs):
            def write(factory):
                writer = factory.create('lying.txt')
                writer.write(b'abc')
                writer.write(b'def')
            yield SimpleNamespace(needs_password=lambda: True,
                list=lambda: [SimpleNamespace(filename='lying.txt', is_symlink=False,
                    is_directory=False, is_file=True, uncompressed=1)],
                extractall=lambda factory: write(factory))

        with patch('py7zr.SevenZipFile', reader), self.assertRaises(ArchiveRejected):
            extract_archive(path, self.root / 'out', password='correct', limits=Limits(max_total=4, min_free=0))
        self.assertEqual((self.root / 'out' / 'lying.txt').read_bytes(), b'abc')


    def test_wrong_password_with_other_supported_7z_codecs_is_retryable(self):
        for codec in [py7zr.FILTER_DEFLATE, py7zr.FILTER_BZIP2, py7zr.FILTER_ZSTD, py7zr.FILTER_BROTLI]:
            with self.subTest(codec=codec):
                path = self.root / 'codec.7z'
                with py7zr.SevenZipFile(path, 'w', password='correct', filters=[
                        {'id': codec}, {'id': py7zr.FILTER_CRYPTO_AES256_SHA256}]) as archive:
                    archive.writestr(b'hello world' * 100, 'a.txt')
                with self.assertRaises(PasswordNeeded):
                    extract_archive(path, self.root / f'bad-{codec}', password='wrong', limits=Limits(min_free=0))
                files = extract_archive(path, self.root / str(codec), password='correct', limits=Limits(min_free=0))
                self.assertEqual(files[0].read_bytes(), b'hello world' * 100)

    def test_plain_corrupt_7z_does_not_become_password_prompt_when_caption_exists(self):
        path = self.root / 'plain.7z'
        with py7zr.SevenZipFile(path, 'w') as archive:
            archive.writestr(b'hello', 'a.txt')
        data = bytearray(path.read_bytes())
        data[-1] ^= 255
        path.write_bytes(data)
        try:
            extract_archive(path, self.root / 'out', password='unused-caption', limits=Limits(min_free=0))
        except PasswordNeeded:
            self.fail('A corrupt plain archive must not ask for a password')
        except ArchiveRejected:
            pass
        else:
            self.fail('Corrupt header should fail')

    def test_filesystem_errors_remain_fatal_for_encrypted_7z(self):
        import errno
        path = self.root / 'fake.7z'
        path.write_bytes(b'7z\xbc\xaf\x27\x1c')

        @contextmanager
        def reader(*args, **kwargs):
            def write(factory):
                raise OSError(errno.ENOSPC, 'no space left')
            yield SimpleNamespace(needs_password=lambda: True,
                list=lambda: [SimpleNamespace(filename='a.txt', is_symlink=False,
                    is_directory=False, is_file=True, uncompressed=1)],
                extractall=lambda factory: write(factory))

        with patch('py7zr.SevenZipFile', reader), self.assertRaises(OSError):
            extract_archive(path, self.root / 'out', password='correct', limits=Limits(min_free=0))


if __name__ == '__main__':
    unittest.main()
